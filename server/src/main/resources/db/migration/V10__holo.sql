-- A2 医保数据公开全息图 / B1 本院全息图（holo 分组）
-- 只存聚合结果（病组级、地区级），不含病例级字段。半径、色阶、关键少数、外环、口径换算、占比等派生数字由分析引擎计算。

-- ---------------------------------------------------------------- A2 病组气泡（全市，月均口径）
create table holo_drg (
    code             varchar(8)   primary key,
    name             varchar(48)  not null,
    cases            int          not null,             -- 月均出院病例数（全市）
    avg_diff         int          not null,             -- 例均基金差额（元）= 医保记账 − DRG 支付标准；正为逆差
    avg_cost         int          not null,             -- 次均总费用（元）
    surgical         boolean      not null,
    time_index       numeric(4,2) not null,             -- 时间消耗指数（“效”图层：> 1.10 加橙色外环）
    audit_deduct_wan numeric(6,1) not null,             -- 本期审核扣款（万元）
    upcode_cases     int          not null,             -- 疑似高套病例数（“错”图层：扣款 ≥ 10 万或疑似高套 ≥ 20 例加红色外环）
    cost_mix         jsonb        not null,             -- 本组费用结构 % [药品, 耗材, 检查检验, 治疗/手术, 护理及其他]
    bench_mix        jsonb        not null,             -- 标杆组费用结构 %
    peer_pct         int          not null,             -- 全省 8 个统筹区同组次均费用中本统筹区所处分位
    sort             int          not null
);

create table holo_drg_behavior (
    code        varchar(8)   not null references holo_drg(code),
    sort        int          not null,
    name        varchar(32)  not null,
    rate_pct    numeric(5,1) not null,                  -- 发生率 %
    multiplier  numeric(3,1) not null,                  -- 费用倍率（有该行为次均 / 无该行为次均）
    primary key (code, sort)
);

create table holo_drg_gap (
    code    varchar(8)    not null references holo_drg(code),
    sort    int           not null,
    metric  varchar(16)   not null,
    value   numeric(10,1) not null,                     -- 本组
    bench   numeric(10,1) not null,                     -- 标杆组
    unit    varchar(4)    not null,
    kind    varchar(8)    not null check (kind in ('ratio', 'diff', 'pt')),   -- 差距口径：相对比例 / 绝对差 / 百分点
    primary key (code, sort)
);

-- ---------------------------------------------------------------- A2 区域外（省平台回流，地区汇总）
create table holo_offsite (
    id           int primary key check (id = 1),
    fund_share   numeric(4,1) not null,                 -- 占全市统筹基金支出 %
    visits       int          not null,                 -- 人次
    source       varchar(48)  not null
);

create table holo_flow (
    sort        int primary key,
    region      varchar(16)   not null,
    scope       varchar(4)    not null check (scope in ('省内', '省外', '其他')),
    amount_wan  numeric(10,1) not null                  -- 基金支出（万元），占比由引擎计算
);

create table holo_offsite_level (sort int primary key, name varchar(8) not null, pct int not null);
create table holo_offsite_disease (sort int primary key, name varchar(24) not null, pct numeric(4,1) not null);
-- 就医地机构排名：仅医保局可见，不进入发布区（机构门户只显示地区汇总）
create table holo_offsite_rank (sort int primary key, facility varchar(32) not null, visits int not null);

-- ---------------------------------------------------------------- A2 公开状态（公开目录 × 受众）
create table holo_pub_audience (sort int primary key, name varchar(8) not null);
create table holo_pub_indicator (sort int primary key, name varchar(24) not null, grp varchar(8) not null);
create table holo_pub_cell (
    indicator_sort int        not null references holo_pub_indicator(sort),
    audience_sort  int        not null references holo_pub_audience(sort),
    state          varchar(4) not null check (state in ('PUB', 'NP', 'CMT', 'INT', 'NA')),  -- 已发 / 应公开未公开 / 意见未复 / 仅内部 / 不适用
    value          int,                                 -- PUB：查阅率 %；CMT：未答复意见条数
    primary key (indicator_sort, audience_sort)
);

create table holo_pub_status (
    id          int primary key check (id = 1),
    target      varchar(32) not null,
    tier        varchar(32) not null,
    latest      varchar(32) not null,
    sign_pct    int not null,
    read_pct    int not null,
    opinions    int not null,
    replied     int not null,
    overdue     int not null
);

create table holo_shortcut (sort int primary key, kind varchar(8) not null, title varchar(16) not null, sub varchar(48));

-- ---------------------------------------------------------------- B1 本院全息图
create table holo_org (
    code         varchar(8)    primary key,
    name         varchar(32)   not null unique,         -- 与会话身份的机构名称对应
    tier         varchar(8)    not null,                -- 同级组
    peer_count   int           not null,                -- 同级机构数（< 5 家不输出同级分位）
    period       varchar(16)   not null,
    tier_mode    varchar(8)    not null,                -- 对标档位
    pending_sign varchar(32),
    alert        varchar(32),
    ledger_wan   numeric(10,1) not null,                -- 医保记账总额（万元）
    drg_pay_wan  numeric(10,1) not null,                -- DRG 支付总额（万元）
    cases        int           not null,                -- 本期出院病例数
    diff_pct     int           not null                 -- 例均基金差额的同级分位
);

-- 本院病组（本院数据，具名）
create table holo_org_drg (
    org_code  varchar(8) not null references holo_org(code),
    code      varchar(8) not null references holo_drg(code),
    cases     int        not null,
    avg_diff  int        not null,
    primary key (org_code, code)
);

-- 全市同级机构同组均值（灰色背景；只有病组编码与均值，不含任何机构字段）
create table holo_peer_drg (
    tier       varchar(8)   not null,
    code       varchar(8)   not null references holo_drg(code),
    avg_cases  numeric(7,1) not null,
    avg_diff   int          not null,
    primary key (tier, code)
);

create table holo_org_indicator (
    org_code     varchar(8)  not null references holo_org(code),
    sort         int         not null,
    name         varchar(16) not null,
    value        varchar(16) not null,
    unit         varchar(4)  not null,
    pct          int         not null,                  -- 同级匿名分位
    higher_worse boolean     not null,                  -- 高为差：≥ P70 标橙
    primary key (org_code, sort)
);

create table holo_org_trend (
    org_code  varchar(8)  not null references holo_org(code),
    sort      int         not null,
    month     varchar(4)  not null,
    avg_diff  int         not null,
    primary key (org_code, sort)
);

