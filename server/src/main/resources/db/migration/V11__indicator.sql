-- 指标配置（A4）与智能推荐（A6）。表名前缀 ind_ / rec_；只读第二批表：data_source（到数状态 → 本期暂缓）、
-- benchmark_tier / tier_change_request（A13 对标档位）、indicator_lineage（A3 血缘）、org_quality（A3 清单质控率）、chart_template（A5 模板名）。

-- ---------------------------------------------------------------- 机构与同级分组（预览、标杆计算用）
create table ind_peer_group (
    name varchar(8) primary key,                  -- 市三级 / 县三级 / 二级甲等 / 二级其他 / 一级
    sort int        not null
);

create table ind_org (
    name       varchar(64) primary key,
    peer_group varchar(8)  not null references ind_peer_group(name),
    district   varchar(8)  not null,
    sort       int         not null
);

-- ---------------------------------------------------------------- 指标目录（A4 列表 / 指标卡）
create table ind_indicator (
    id           bigserial primary key,
    code         varchar(16)  not null unique,
    name         varchar(32)  not null unique,
    grp          varchar(4)   not null,           -- 钱 / 效 / 错
    domain       varchar(16)  not null,           -- 主题域
    source       varchar(32)  not null,           -- 数据来源（= A3 数据源名称；未按时到达 → 本期暂缓）
    freq         varchar(4)   not null,
    tier         int,                             -- 0 匿名分位 / 1 匿名编号 / 2 具名PK与排行；仅内部为空
    scope        varchar(32)  not null,           -- 可见范围
    version      varchar(8)   not null,
    status       varchar(8)   not null,           -- 已上线 / 审批中 / 草稿
    tag          varchar(4)   not null,           -- 必选（国家底稿）/ 增选（地方）/ 仅内部
    owner        varchar(64)  not null,
    formula      varchar(512) not null,
    rule_version varchar(128) not null,           -- 取数规则版本
    batch_no     varchar(16)  not null,
    source_tables varchar(128) not null,
    created_at   timestamptz  not null default now(),
    sort         int          not null
);
create index ix_ind_indicator_grp on ind_indicator(grp, sort);

create table ind_change_log (
    id           bigserial primary key,
    indicator_id bigint      not null references ind_indicator(id),
    label        varchar(16) not null,            -- v2.1 / 上一版 / 初版
    changed_on   date        not null,
    author       varchar(32) not null,
    note         varchar(128) not null,
    sort         int         not null
);

-- 发布包（本组只登记“加入发布包”，A8 发布工作流读取）
create table ind_package_item (
    indicator_id bigint      not null references ind_indicator(id),
    package      varchar(32) not null,
    added_by     bigint      not null references app_user(id),
    added_at     timestamptz not null default now(),
    primary key (indicator_id, package)
);

-- ---------------------------------------------------------------- 新建指标向导
create table ind_atom (
    name  varchar(16) primary key,                -- 原子指标
    unit  varchar(8)  not null,
    cases int         not null,                   -- 本期可取数例数（预计取数）
    source varchar(32) not null,                  -- 来源数据源（A3）
    sort  int         not null
);

-- 预览取数（按 分子 / 分母 原子指标组合 × 机构），用于“以机构身份预览”
create table ind_preview_value (
    numerator   varchar(16)  not null references ind_atom(name),
    denominator varchar(16)  not null references ind_atom(name),
    org         varchar(64)  not null references ind_org(name),
    value       numeric(8,2) not null,
    cases       int          not null,
    primary key (numerator, denominator, org)
);

create table ind_draft (
    id           bigserial primary key,
    created_by   bigint      not null references app_user(id),
    config       jsonb       not null,
    version      varchar(8)  not null default 'v0.1',
    saved_at     timestamptz not null default now(),
    submitted_at timestamptz,
    approval_no  varchar(16) unique,              -- 上线审批单号 ZB-YYYY-NNNN
    indicator_id bigint references ind_indicator(id)
);
create sequence ind_approval_seq start 917;

-- ---------------------------------------------------------------- 智能推荐（A6）
create table rec_topic (
    code         varchar(8)   primary key,
    name         varchar(32)  not null,
    period       varchar(16)  not null,
    f_case       int not null, f_amount int not null, f_trend int not null, f_fund int not null,
    f_attention  int not null, f_recommend int not null, f_admit_z int not null,   -- 分项得分 0–100（引擎加权）
    status       varchar(8)   not null default 'CAND',   -- CAND 候选 / ADOPT 已采纳 / REJECT 已否决
    reasons_override jsonb,                               -- 人工修改后的入选理由
    note         varchar(256),                            -- 人工修改的选题范围说明
    decided_by   bigint references app_user(id),
    decided_at   timestamptz,
    sort         int          not null
);

create table rec_attribution (
    code            varchar(8)   primary key,
    name            varchar(32)  not null,
    patient_diff    int          not null,       -- 例均费用差异中的患者差异（元）
    behavior_diff   int          not null,       -- 行为差异（元）
    behaviors       jsonb        not null,       -- [{name, amount}]
    comorbidity_pct numeric(5,1) not null,       -- 合并症编码率
    cases           int          not null,
    qc_org          varchar(64),                 -- 结算清单质控率最低的机构（读 A3 org_quality）
    sort            int          not null
);

create table rec_bench_org (
    org      varchar(64)  primary key references ind_org(name),
    avg_cost int          not null,              -- 例均费用（元）
    qc_pct   numeric(4,1) not null               -- 结算清单质控率
);

create table rec_anomaly (
    id           bigserial primary key,
    rule_name    varchar(32) not null,
    org          varchar(64) not null,           -- 仅医保局可见
    drg_group    varchar(32) not null,
    trigger_value varchar(32) not null,
    level        varchar(4)  not null,           -- 关注 / 预警
    letter_no    varchar(16) unique,             -- 提醒函草稿编号
    letter_by    bigint references app_user(id),
    letter_at    timestamptz,
    sort         int         not null
);
create sequence rec_letter_seq start 1;

create table rec_presentation (
    id        bigserial primary key,
    indicator varchar(32) not null,
    chart     varchar(16) not null,
    reason    varchar(128) not null,
    sort      int         not null
);

create table rec_method (
    tab   varchar(8)  primary key,               -- topic / attr / bench / anom / pres
    title varchar(16) not null,
    rows  jsonb       not null                   -- [[适用条件, …], [样本量, …], [拟合度, …], [已知局限, …]]
);

